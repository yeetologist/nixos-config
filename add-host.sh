#!/usr/bin/env bash
# Create hosts/<name>/ for the machine this runs on (installer ISO or an installed NixOS).
#   cd nixos-config && bash add-host.sh laptop
# Detects drivers with nixos-generate-config and enables battery/Bluetooth support if present.
# The flake picks up every folder in hosts/, so no flake.nix edit is needed.
set -euo pipefail

die() { echo "error: $*" >&2; exit 1; }
name=${1:-}
[[ $name =~ ^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$ ]] || die "usage: add-host.sh <name>  (lowercase letters, digits, '-')"
cd "$(dirname "$0")"
[ -f flake.nix ] && [ -f hosts/disk.nix ] || die "run from the nixos-config repo"
[ ! -e "hosts/$name" ] || die "hosts/$name already exists"
command -v nixos-generate-config >/dev/null || die "nixos-generate-config not found (run on NixOS or the installer ISO)"
gen=nixos-generate-config
[ "$(id -u)" = 0 ] || gen="sudo nixos-generate-config" # needs root to probe btrfs; files stay yours

mkdir "hosts/$name"
trap '[ -f "hosts/$name/default.nix" ] || rm -rf "hosts/$name"' EXIT # don't leave a half-made host

{
  echo "# Generated by \`nixos-generate-config --show-hardware-config --no-filesystems\` on $(date +%F)."
  echo "# Disks live in ../disk.nix. Regenerate rather than hand-edit."
  $gen --show-hardware-config --no-filesystems | sed '/^# Do not modify this file/,/^# to \/etc\/nixos/d'
} > "hosts/$name/hardware-configuration.nix"

# Detected extras: uncommented when the hardware is present.
on() { if eval "$1"; then echo "  $2"; else echo "  # $2"; fi; }
has_battery='ls /sys/class/power_supply/BAT* >/dev/null 2>&1'
has_bt='[ -d /sys/class/bluetooth ] && [ -n "$(ls -A /sys/class/bluetooth)" ]'
has_nvidia='grep -qs 0x10de /sys/bus/pci/devices/*/vendor'

{
  cat <<EOF
# Host $name: hardware-specific settings only. Shared config: ../../configuration.nix, ../../home.nix.
{ pkgs, user, ... }:

{
  imports = [ ../disk.nix ./hardware-configuration.nix ];

EOF
  on "$has_battery" 'services.power-profiles-daemon.enable = true; # battery: power profiles'
  on "$has_battery" 'services.upower.enable = true;                # battery status for waybar etc.'
  on "$has_bt"      'hardware.bluetooth.enable = true;'
  on "$has_nvidia"  'hardware.nvidia.open = true; services.xserver.videoDrivers = [ "nvidia" ]; # NVIDIA GPU'
  cat <<EOF

  # Host-only Home Manager settings: create ./home.nix, then uncomment.
  # home-manager.users.\${user}.imports = [ ./home.nix ];
}
EOF
} > "hosts/$name/default.nix"

git add "hosts/$name" # flakes only see files git tracks
echo "Created hosts/$name/ (staged):"
sed -n '/^{ pkgs/,$p' "hosts/$name/default.nix"
echo
echo "Next: review it (nano hosts/$name/default.nix), then install or rebuild with #$name."
